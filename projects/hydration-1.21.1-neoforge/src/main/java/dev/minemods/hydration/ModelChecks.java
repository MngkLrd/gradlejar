package dev.minemods.hydration;
import static dev.minemods.hydration.WaterBalance.*;
public final class ModelChecks {
 private static void check(boolean yes,String message){if(!yes)throw new IllegalStateException("Hydration regression: "+message);}
 public static void run(){
  var s=new State(40,0);
  var d=drink(s,Quality.DRINKABLE,250,0);
  check(d.water()==40&&d.pending()==20,"fresh water pending not instant");
  var a=tick(d,0);check(a.water()>40&&a.pending()<20,"absorption");
  for(int i=0;i<40;i++)a=tick(a,0);
  check(Math.abs(a.water()-60)<.001&&a.pending()<.001,"total absorption conserved");
  check(drink(s,Quality.DESALINATE,250,.3).water()==35,"salt water loses water");
  check(drink(s,Quality.UNKNOWN,250,-1).exposure()>0,"unknown not safe");
  check(drink(s,Quality.TREAT_RECOMMENDED,250,.7).exposure()>drink(s,Quality.TREAT_RECOMMENDED,250,.2).exposure(),"risk");
  check(drink(s,Quality.NOT_WATER,250,0).equals(s),"nonwater");
  check(drink(s,Quality.DRINKABLE,Double.NaN,0).equals(s),"invalid dose");
  var full=drink(new State(100,0),Quality.DRINKABLE,1000,0);
  check(full.pending()==25&&!canDrink(full),"overfill rejected");
  for(int i=0;i<60;i++)full=tick(full,0);
  check(Math.abs(full.reserve()-25)<.001&&full.water()==100,"reserve");
  check(tick(full,1).water()==100&&tick(full,1).reserve()<25,"reserve first");
  check(tick(new State(0,0),1).water()==0,"min");
  check(loss(40,20,true,true,false,false,1)>loss(20,50,false,false,false,true,0),"heat and effort");
  check(loss(40,20,false,false,false,true,0)>loss(40,90,false,false,false,true,0),"humidity");
  check(loss(20,50,true,false,false,true,0)>loss(20,50,false,false,false,true,0),"walking");
  check(loss(40,50,false,false,false,false,1,37,0)==loss(20,50,false,false,false,true,0,37,0),"thermal replaces ambient heat");
  check(loss(20,50,false,false,false,true,0,39,0)>loss(20,50,false,false,false,true,0,37,0),"body temperature");
  check(loss(20,50,false,false,false,true,0,37,4)>loss(20,50,false,false,false,true,0,37,0),"bleeding");
  check(halfUnits(0)==0&&halfUnits(1)==1&&halfUnits(50)==10&&halfUnits(100)==20,"HUD boundaries");
  check(FluidUnits.BUCKET_MB==1000&&FluidUnits.SIP_MB*4==FluidUnits.BUCKET_MB,"Minecraft fluid units");
  var sea=new WaterBatch(FluidUnits.BUCKET_MB,Quality.DESALINATE,35,.3,java.util.Set.of("SEA"));
  check(sea.mB()==FluidUnits.BUCKET_MB&&sea.mB()==sea.ml(),"legacy amount compatibility");
  var fresh=new WaterBatch(500,Quality.DRINKABLE,.2,.1,java.util.Set.of("RIVER"));
  var t=WaterBatch.transfer(sea,fresh,750,1000);
  check(t.moved()==500&&t.source().ml()==500&&t.target().ml()==1000,"volume conservation/capacity");
  check(Math.abs(t.target().salinity()*1000+t.source().salinity()*500-(35*1000+.2*500))<.001,"salt mass conservation");
  check(Math.abs(t.target().risk()*1000+t.source().risk()*500-(.3*1000+.1*500))<.001,"contamination conservation");
  check(t.target().quality()==Quality.DESALINATE,"salt cannot be laundered");
  check(t.target().origins().equals(java.util.Set.of("SEA","RIVER"))&&t.source().origins().equals(java.util.Set.of("SEA")),"provenance survives mixing and split");
  check(WaterBatch.transfer(sea,t.target(),100,1000).moved()==0,"full target");
  check(WaterTreatment.filter(sea).salinity()==35&&WaterTreatment.filter(sea).quality()==Quality.DESALINATE,"filter retains salt");
  var boiled=WaterTreatment.boil(sea);check(boiled.ml()==950&&boiled.quality()==Quality.DESALINATE&&Math.abs(boiled.salinity()*boiled.ml()-35000)<.001,"boil retains salt");
  var distilled=WaterTreatment.distill(sea);check(distilled.ml()==700&&distilled.salinity()==0&&distilled.quality()==Quality.DRINKABLE&&distilled.origins().equals(sea.origins()),"distill");
  var swamp=new WaterBatch(1000,Quality.TREAT_RECOMMENDED,.2,.9,java.util.Set.of("WETLAND"));
  check(WaterTreatment.filter(swamp).quality()==Quality.TREAT_RECOMMENDED&&WaterTreatment.boil(swamp).quality()==Quality.TREAT_RECOMMENDED,"individual steps");
  check(WaterTreatment.boil(WaterTreatment.filter(swamp)).quality()==Quality.DRINKABLE,"combined treatment");
  var down=GravityFlow.move(sea,fresh,1000,12,10,0,false);
  check(down.moved()==250&&down.source().ml()==750&&down.target().ml()==750,"gravity rate and conservation");
  check(GravityFlow.move(sea,fresh,1000,10,10,0,false).moved()==0,"no level flow");
  check(GravityFlow.move(sea,fresh,1000,10,11,0,false).moved()==0,"no uphill flow");
  check(GravityFlow.move(sea,fresh,500,12,10,0,false).moved()==0,"full target");
  check(GravityFlow.move(sea,fresh,1000,12,10,0,true).moved()==0,"filter depleted");
  var filtered=GravityFlow.move(sea,WaterBatch.empty(),1000,12,10,100,true);
  check(filtered.moved()==100&&filtered.remainingFilter()==0&&filtered.target().salinity()==35&&filtered.target().risk()<sea.risk(),"filter consumption limited by actual throughput");
  check(GravityFlow.rainMl(false,true,1)==0&&GravityFlow.rainMl(true,false,1)==0&&GravityFlow.rainMl(true,true,0)==0&&GravityFlow.rainMl(true,true,.5)==30,"rain boundaries");
  var clean=new WaterBatch(1000,Quality.DRINKABLE,.2,.08,java.util.Set.of("SPRING"),100);
  var open=clean.aged(100+24000L*10,true);var closed=clean.aged(100+24000L*10,false);
  check(open.risk()>closed.risk()&&closed.risk()>clean.risk(),"exposed storage spoils faster");
  check(open.ml()==clean.ml()&&open.salinity()==clean.salinity()&&open.origins().equals(clean.origins()),"spoilage retains mass and provenance");
  check(open.quality()==Quality.TREAT_RECOMMENDED&&WaterTreatment.boil(open).risk()<open.risk(),"stale water downgrade and treatment");
  check(clean.aged(100,true).equals(clean)&&clean.aged(0,true).risk()==clean.risk(),"same tick and time rollback");
  check(new WaterBatch(250,Quality.DRINKABLE,0,.1).aged(999999,true).risk()==.1,"legacy timestamp starts now");
  check(Math.abs(clean.aged(24100,true).aged(48100,true).risk()-clean.aged(48100,true).risk())<.0000001,"storage rate independent of update interval");
  var agedMix=WaterBatch.transfer(open,closed,500,1500);check(agedMix.moved()==500&&Math.abs(agedMix.target().risk()*1500+agedMix.source().risk()*500-(open.risk()*1000+closed.risk()*1000))<.001,"aged mix conserves risk");
  check(drink(s,Quality.DRINKABLE,250,.01,.1).pending()>drink(s,Quality.TREAT_RECOMMENDED,250,.6,.1).pending(),"quality alters hydration gain");
  check(drink(s,Quality.DRINKABLE,250,.1,.1).pending()>drink(s,Quality.DESALINATE,250,.1,5).pending(),"numeric salt reduces restoration");
  check(drink(s,Quality.DESALINATE,250,.1,35).electrolytes()>50,"saline increases electrolyte index");
  check(tick(s,.5).electrolytes()<s.electrolytes()&&eat(new State(40,0,0,0,30),4).electrolytes()>30,"electrolyte loss and food recovery");
  check(stage(70)==Dehydration.NORMAL&&stage(50)==Dehydration.MILD&&stage(25)==Dehydration.MODERATE&&stage(10)==Dehydration.SEVERE&&stage(9)==Dehydration.CRITICAL,"dehydration stages");
  check(illnessLoss(50)>illnessLoss(12)&&illnessLoss(0)==0,"fallback illness fluid loss");
  var unknown=new WaterBatch(100,Quality.UNKNOWN,0,1);
  check(WaterBatch.transfer(unknown,fresh,100,1000).target().quality()==Quality.UNKNOWN,"unknown cannot be laundered");
 }
 public static void main(String[] args){run();System.out.println("HYDRATION_MODEL_CHECKS_PASSED");}
}
