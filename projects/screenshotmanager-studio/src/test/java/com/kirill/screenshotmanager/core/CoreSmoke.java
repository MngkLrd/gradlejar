package com.kirill.screenshotmanager.core;
import java.awt.image.BufferedImage;
import java.nio.file.Files;
import java.util.List;
public final class CoreSmoke {
    private static void check(boolean result,String label){if(!result)throw new AssertionError(label);}
    public static void main(String[] args)throws Exception{
        BufferedImage img=new BufferedImage(40,30,BufferedImage.TYPE_INT_ARGB);
        for(int y=0;y<30;y++)for(int x=0;x<40;x++)img.setRGB(x,y,0xff89abcd);
        var doc=new ImageDocument(img);
        doc.add(ImageDocument.mark(new ImageDocument.Mark(ImageDocument.Tool.REDACT,5,5,15,15,0x00112233,3,8,"",List.of())));
        var edited=doc.render(doc.snapshot());
        check(edited.getRGB(8,8)==0xff112233,"Opaque redaction");
        check(img.getRGB(8,8)==0xff89abcd,"Original untouched");
        doc.undo();check(doc.render(doc.snapshot()).getRGB(8,8)==0xff89abcd,"Undo");
        doc.redo();check(doc.render(doc.snapshot()).getRGB(8,8)==0xff112233,"Redo");
        doc.add(ImageDocument.mark(new ImageDocument.Mark(ImageDocument.Tool.CROP,2,3,20,15,0,2,8,"",List.of())));
        var cropped=doc.render(doc.snapshot());check(cropped.getWidth()==19&&cropped.getHeight()==13,"Crop");
        doc.add(ImageDocument.filter(ImageDocument.Filter.ROTATE));var rotated=doc.render(doc.snapshot());
        check(rotated.getWidth()==13&&rotated.getHeight()==19,"Rotate");
        var layers=new ImageDocument(img);
        layers.add(ImageDocument.mark(new ImageDocument.Mark(ImageDocument.Tool.REDACT,2,2,7,7,0xff000000,1,3,"",List.of())));
        check(layers.toggle(0)&&layers.render(layers.snapshot()).getRGB(4,4)==0xff89abcd,"Hide layer");
        layers.undo();check(layers.render(layers.snapshot()).getRGB(4,4)==0xff000000,"Undo visibility");
        check(layers.translate(0,10,0)&&layers.render(layers.snapshot()).getRGB(14,4)==0xff000000,"Move layer");
        check(layers.render(layers.snapshot()).getRGB(4,4)==0xff89abcd,"Move clears old pixels");
        check(layers.delete(0)&&layers.count()==0,"Delete layer");
        layers.undo();check(layers.count()==1,"Undo delete");
        layers.add(new ImageDocument.Adjustment(30,0,0,0,0,0));
        check(layers.render(layers.snapshot()).getRGB(0,0)!=img.getRGB(0,0),"Color grade");
        check(layers.move(1,-1),"Reorder");
        check(layers.compare(layers.render(layers.snapshot())).getWidth()==88,"Comparison layout");
        var root=Files.createTempDirectory("screenshotmanager-test");var shot=new ShotFiles.Shot(root.resolve("original.png"),0);
        var png=ShotFiles.export(root,shot,rotated,false,0);check(ShotFiles.read(png,0).getWidth()==13,"PNG export");
        var jpg=ShotFiles.export(root,shot,rotated,true,10);check(ShotFiles.read(jpg,0).getHeight()==10,"JPEG resize");
        check(ShotFiles.list(root).size()==2,"Gallery scans edited exports");
        var prefPath=root.resolve("settings.properties");
        var prefs=new StudioPreferences(prefPath,root);
        prefs.toggleFavorite(png);prefs.album(png,"Builds");prefs.number("hud.seconds",8);
        var restored=new StudioPreferences(prefPath,root);
        check(restored.favorite(png)&&restored.album(png).equals("Builds"),"Persist album and favorite");
        check(restored.albums().equals(List.of("Builds"))&&restored.number("hud.seconds",5,2,20)==8,"Persist settings");
        ProjectStore.save(png,layers.snapshot());
        var loaded=ProjectStore.load(png);
        var reopened=new ImageDocument(img);reopened.restore(loaded);
        check(reopened.count()==layers.count(),"Project layer count");
        check(reopened.render(reopened.snapshot()).getRGB(14,4)==layers.render(layers.snapshot()).getRGB(14,4),"Project layer rendering");
        check(reopened.render(reopened.snapshot()).getRGB(0,0)==layers.render(layers.snapshot()).getRGB(0,0),"Project adjustment rendering");
        var custom=CreatorExport.save(root.resolve("edited"),img,true,75,20,20000);
        check(Files.size(custom)<=20000&&ShotFiles.read(custom,0).getWidth()==20,"Custom JPEG export");
        var grid=CreatorExport.collage(List.of(img,rotated),false);
        check(grid.getWidth()==1944&&grid.getHeight()==556,"Collage dimensions");
        var anim=ClipCodec.save(root.resolve("clips"),List.of(new ClipCodec.Frame(img,0),new ClipCodec.Frame(edited,100),new ClipCodec.Frame(img,200)),0,3,10,64,20000);
        check(anim.bytes()<=20000&&anim.frames()==3,"GIF encoding and limit");
        var reader=javax.imageio.ImageIO.getImageReadersByFormatName("gif").next();
        try(var in=javax.imageio.ImageIO.createImageInputStream(anim.path().toFile())){
            reader.setInput(in);check(reader.getNumImages(true)==3,"GIF contains all frames");
        }finally{reader.dispose();}
        Files.delete(anim.path());Files.delete(root.resolve("clips"));
        Files.delete(png.resolveSibling(png.getFileName()+".smproject"));
        Files.delete(custom);Files.delete(prefPath);Files.delete(png);Files.delete(jpg);Files.delete(root.resolve("edited"));Files.delete(root);
        var track=new CameraTrack(List.of(new CameraTrack.Pose(0,64,0,170,0),new CameraTrack.Pose(4,65,3,-170,10),new CameraTrack.Pose(8,66,6,-160,0)));
        check(track.sample(0).x()==0&&track.sample(1).x()==8,"Camera path endpoints");
        check(Math.abs(track.sample(.25).yaw())>160,"Shortest angle interpolation");
        check(track.sample(.5).y()==65,"Camera keyframe interpolation");
        check(track.sample(.2).x()>=0&&track.sample(.8).x()<=8,"Camera path bounds");
        var from=new FlybyPath.Vec(.5,1.5,.5);var to=new FlybyPath.Vec(6.5,1.5,.5);
        var direct=FlybyPath.plan(from,to,v->true);
        check(direct!=null&&direct.sample(0).equals(from)&&direct.sample(1).equals(to),"Flyby direct endpoints");
        java.util.function.Predicate<FlybyPath.Vec> free=v->!(v.x()>2.7&&v.x()<4.3&&Math.abs(v.z()-.5)<1.2&&v.y()<3.2)&&v.y()>0&&v.y()<6;
        var detour=FlybyPath.plan(from,to,free);
        check(detour!=null&&detour.length()>6,"Flyby detours around obstacle");
        for(int i=0;i<=400;i++)check(free.test(detour.sample(i/400.0)),"Flyby collision-free smoothing");
        check(FlybyPath.plan(from,to,v->v.x()<1||v.x()>6)==null,"Flyby rejects enclosed path");
        var brushDoc=new ImageDocument(img);
        brushDoc.add(ImageDocument.mark(new ImageDocument.Mark(ImageDocument.Tool.PEN,4,4,20,4,0xffff0000,5,18,"",List.of())));
        check(brushDoc.render(brushDoc.snapshot()).getRGB(12,4)==0xffff0000,"Pen stroke");
        brushDoc.add(ImageDocument.mark(new ImageDocument.Mark(ImageDocument.Tool.ERASER,12,1,12,8,0xffffffff,5,18,"",List.of())));
        check(brushDoc.render(brushDoc.snapshot()).getRGB(12,4)==img.getRGB(12,4),"Eraser protects original");
        brushDoc.undo();check(brushDoc.render(brushDoc.snapshot()).getRGB(12,4)==0xffff0000,"Undo eraser");
        brushDoc.reset();check(brushDoc.count()==0,"Undo all");
        brushDoc.undo();check(brushDoc.count()==1,"Undo reset");
        check(Math.abs(ProPhoto.curve(128,0,0,0)-128)<.001,"Neutral curve");
        var neutral=new ProPhoto.Tone(new int[ProPhoto.TONE_COUNT]).apply(ImageDocument.copy(img));
        check(neutral.getRGB(0,0)==img.getRGB(0,0),"Neutral tone");
        int[] tone=new int[ProPhoto.TONE_COUNT];tone[0]=45;
        check(new ProPhoto.Tone(tone).apply(ImageDocument.copy(img)).getRGB(0,0)!=img.getRGB(0,0),"Shadow adjustment");
        var proRoot=Files.createTempDirectory("sm-pro-test");var proPng=proRoot.resolve("source.png");
        javax.imageio.ImageIO.write(img,"png",proPng.toFile());
        var imported=ProPhoto.ImageLayer.load(proPng,20,15);
        brushDoc.add(imported);brushDoc.add(new ProPhoto.Tone(tone));
        ProjectStore.save(proPng,brushDoc.snapshot());
        check(ProjectStore.load(proPng).size()==3,"Pro project round trip");
        WorldCapture.save(proPng,new WorldCapture.Scene("minecraft:overworld",1,64,2,0,0,70,1000,false,false,true,123));
        check(WorldCapture.read(proPng).contains("minecraft:overworld"),"Scene metadata");
        Files.delete(proPng.resolveSibling("source.png.world.json"));Files.delete(proPng.resolveSibling("source.png.smproject"));Files.delete(proPng);Files.delete(proRoot);
        System.out.println("Screenshot Manager core smoke tests passed");
    }
}
