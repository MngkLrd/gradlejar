def rgba(c):return tuple(bytes.fromhex(c))+(255,) if len(c)==6 else tuple(bytes.fromhex(c))
def write(path,rows,pal,w=16,h=16):
    assert len(rows)==h and all(len(r)==w for r in rows),(path,[len(r) for r in rows])
    raw=b"".join(b"\0"+b"".join(bytes(pal[c]) for c in r) for r in rows)
    def chunk(k,d):return struct.pack(">I",len(d))+k+d+struct.pack(">I",zlib.crc32(k+d)&0xffffffff)
    dest=ROOT/(path+".png");dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_bytes(b"\x89PNG\r\n\x1a\n"+chunk(b"IHDR",struct.pack(">IIBBBBB",w,h,8,6,0,0,0))+chunk(b"IDAT",zlib.compress(raw,9))+chunk(b"IEND",b""))
def palette(*cs):return {".":(0,0,0,0),**{str(i):rgba(c) for i,c in enumerate(cs)}}
def map16(path,pal,pattern):
    # Each row is deliberately drawn; spaces are transparent padding.
    rows=[r.replace(" ","") for r in pattern.strip().splitlines()]
    assert len(rows)==16,(path,len(rows))
    write(path,[r.ljust(16,".") for r in rows],pal)
