# 8 growth stages: coherent leaves, branches, berries with clean silhouette.
# Grow from stem, add individual leaf clusters. All positions are hand assigned.
def canvas(w=16,h=16,c="."):return [[c]*w for _ in range(h)]
def put(a,x,y,c):
    if 0<=y<len(a) and 0<=x<len(a[y]):a[y][x]=c
def stamp(a,x,y,rows):
    for j,r in enumerate(rows.split("/")):
        for i,c in enumerate(r):
            if c!=".":put(a,x+i,y+j,c)
def save(n,a,p):write(n,["".join(r) for r in a],p,len(a[0]),len(a))
