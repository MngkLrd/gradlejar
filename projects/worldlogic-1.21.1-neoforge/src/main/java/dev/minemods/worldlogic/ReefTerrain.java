package dev.minemods.worldlogic;
import java.util.*;
import net.minecraft.core.BlockPos;
import net.minecraft.core.RegistryAccess;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.tags.FluidTags;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.ChunkAccess;
import net.minecraft.world.level.levelgen.*;
import dev.minemods.worldlogic.api.WorldLogicApi.WaterKind;
/** Solid vanilla coral colonies on native seawater reef shelves. No waterlogged
 * vanilla fan/pickle state is generated by this pass. */
public final class ReefTerrain{
 private ReefTerrain(){}
 private static final Block[] CORALS={Blocks.TUBE_CORAL_BLOCK,Blocks.BRAIN_CORAL_BLOCK,Blocks.BUBBLE_CORAL_BLOCK,Blocks.FIRE_CORAL_BLOCK,Blocks.HORN_CORAL_BLOCK};
 static boolean coral(BlockState s){for(var b:CORALS)if(s.is(b))return true;return false;}
 static boolean warm(String id){return id.equals("tropical_ocean")||id.equals("subtropical_ocean")||id.equals("warm_deep_ocean");}
 static int colonyHeight(CoastalTerrain.Zone zone,double patch,double detail){
  double threshold=switch(zone){case BARRIER->.31;case FRINGE->.42;case PATCH->.58;default->1.1;};
  if(patch<threshold)return 0;
  return 1+(detail>.68?1:0)+(zone==CoastalTerrain.Zone.BARRIER&&patch>.78&&detail>.82?1:0);
 }
 static int place(ChunkAccess c,int x,int z,int floor,int sea,int height,int species){
  if(height<1||floor<sea-25||floor+height>sea-3)return 0;
  var p=new BlockPos.MutableBlockPos();var bed=c.getBlockState(p.set(x,floor,z));
  if(!RiverTerrain.natural(bed)||bed.is(Blocks.ICE)||bed.is(Blocks.PACKED_ICE)||bed.is(Blocks.BLUE_ICE))return 0;
  // A contiguous seawater column must remain above the living colony.
  for(int y=floor+1;y<=floor+height+1;y++)if(!MarinePlants.seawater(c.getBlockState(p.set(x,y,z))))return 0;
  var b=CORALS[Math.floorMod(species,CORALS.length)].defaultBlockState();
  for(int y=floor+1;y<=floor+height;y++)c.setBlockState(p.set(x,y,z),b,false);
  return height;
 }
 public static void decorate(NoiseBasedChunkGenerator gen,RandomState state,RegistryAccess access,ChunkAccess c,long seed){
  if(!NaturalWaterGeneration.enabled(gen))return;
  int sea=gen.getSeaLevel(),x0=c.getPos().getMinBlockX(),z0=c.getPos().getMinBlockZ();
  boolean eligible=false;
  for(int x=0;x<16&&!eligible;x+=4)for(int z=0;z<16;z+=4)if(warm(c.getNoiseBiome((x0+x)>>2,(sea-1)>>2,(z0+z)>>2).unwrapKey().orElseThrow().location().getPath())){eligible=true;break;}
  if(!eligible)return;
  var f=CoastalTerrain.field(GeoDensity.riverModel(state,access),seed);
  for(int x=0;x<16;x++)for(int z=0;z<16;z++){
   int wx=x0+x,wz=z0+z,h=c.getHeight(Heightmap.Types.OCEAN_FLOOR_WG,x,z);
   String biome=c.getNoiseBiome(wx>>2,(sea-1)>>2,wz>>2).unwrapKey().orElseThrow().location().getPath();
   if(!warm(biome))continue;
   var zone=CoastalTerrain.zone(f.apply(wx,wz),sea-h);
   int n=colonyHeight(zone,CoastalTerrain.noise(seed^0x698aeL,wx,wz,9),CoastalTerrain.noise(seed^0x28c1L,wx,wz,3));
   if(n==0)continue;
   int species=Math.min(4,(int)(CoastalTerrain.noise(seed^0x97f6L,wx,wz,13)*5));
   place(c,wx,wz,h,sea,n,species);
  }
 }
 static String audit(ServerLevel l,BlockPos origin){
  var c=l.getChunkSource().getChunkNow(origin.getX()>>4,origin.getZ()>>4);if(c==null)return "REEF_AUDIT unavailable";
  int colonies=0,live=0,wrong=0,sea=l.getSeaLevel();Set<Block> species=new HashSet<>();
  var p=new BlockPos.MutableBlockPos();
  for(int x=0;x<16;x++)for(int z=0;z<16;z++){
   int wx=c.getPos().getMinBlockX()+x,wz=c.getPos().getMinBlockZ()+z;
   boolean found=false;
   for(int y=sea-25;y<=sea-3;y++){
    var s=c.getBlockState(p.set(wx,y,wz));if(!coral(s))continue;
    found=true;live++;species.add(s.getBlock());
    if(!warm(l.getBiome(p).unwrapKey().orElseThrow().location().getPath())||!l.getFluidState(new BlockPos(wx,sea-1,wz)).is(FluidTags.WATER))wrong++;
   }
   if(found)colonies++;
  }
  return "REEF_AUDIT colonies="+colonies+" live="+live+" species="+species.size()+" wrong="+wrong;
 }
 static void verify(ServerLevel l){
  CoastalTerrain.verify();
  if(colonyHeight(CoastalTerrain.Zone.LAGOON,.99,.99)!=0||colonyHeight(CoastalTerrain.Zone.BARRIER,.9,.9)!=3||warm("cold_ocean"))throw new IllegalStateException("coral habitat");
  var c=new net.minecraft.world.level.chunk.ProtoChunk(new net.minecraft.world.level.ChunkPos(0,0),net.minecraft.world.level.chunk.UpgradeData.EMPTY,net.minecraft.world.level.LevelHeightAccessor.create(-256,768),l.registryAccess().registryOrThrow(net.minecraft.core.registries.Registries.BIOME),null);
  var p=new BlockPos.MutableBlockPos();var sea=NaturalFluids.get(WaterKind.SEA).block.get().defaultBlockState();
  for(int x=0;x<16;x++)for(int z=0;z<16;z++){for(int y=46;y<=50;y++)c.setBlockState(p.set(x,y,z),Blocks.STONE.defaultBlockState(),false);for(int y=51;y<=62;y++)c.setBlockState(p.set(x,y,z),sea,false);}
  if(!CoastalTerrain.reshape(c,2,2,50,5,63)||!c.getBlockState(p.set(2,55,2)).is(Blocks.CALCITE)||!MarinePlants.seawater(c.getBlockState(p.set(2,56,2))))throw new IllegalStateException("submerged reef framework");
  for(int i=0;i<5;i++){
   if(place(c,i+4,4,50,63,2,i)!=2||!c.getBlockState(p.set(i+4,52,4)).is(CORALS[i])||!MarinePlants.seawater(c.getBlockState(p.set(i+4,53,4))))throw new IllegalStateException("actual coral and native sea "+i);
  }
  c.setBlockState(p.set(12,51,4),Blocks.WATER.defaultBlockState(),false);
  if(place(c,12,4,50,63,2,0)!=0)throw new IllegalStateException("non-native water negative control");
 }
}
